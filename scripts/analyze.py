#!/usr/bin/env python3
"""Collect synthesis / P&R / simulation numbers into tables and figures.
Outputs: docs/results_summary.md, docs/*.csv, docs/figures/*.png"""
import re, json, pathlib, csv
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = pathlib.Path(__file__).resolve().parent.parent
REP, FIG, DOC = ROOT/"synth/reports", ROOT/"docs/figures", ROOT/"docs"
FIG.mkdir(parents=True, exist_ok=True)

def cells(path):
    d = {}
    for m in re.finditer(r"^\s+(\d+)\s+(?:[\d.]+\s+)?\$?(\S+)\s*$", path.read_text(), re.M):
        d[m.group(2)] = d.get(m.group(2), 0) + int(m.group(1))
    return d

def pnr_util(tag, what):
    m = re.search(rf"Total {what}:\s+(\d+)/", (REP/f"{tag}_pnr.log").read_text())
    return int(m.group(1)) if m else 0

def fmax(tag):
    log = (REP/f"{tag}_pnr.log").read_text()
    v = re.findall(r"Max frequency for clock '\$glbnet\$clk[^']*': ([\d.]+) MHz", log)
    return float(v[-1]) if v else None

designs = [("systolic_top_N3", "Systolic 3x3"), ("systolic_top_N4", "Systolic 4x4"),
           ("systolic_top_N4_pipe", "Systolic 4x4 (pipelined MAC)"),
           ("sequential_matmul_N3", "Sequential 1-MAC (N=3)"), ("sequential_matmul_N4", "Sequential 1-MAC (N=4)")]
rows = []
for tag, name in designs:
    x = cells(REP/f"{tag}_xc7_stat.txt"); e = cells(REP/f"{tag}_ecp5_stat.txt")
    lut = sum(v for k, v in x.items() if re.fullmatch(r"LUT\d", k))
    ff  = sum(v for k, v in x.items() if k.startswith("FD"))
    rows.append(dict(design=name, tag=tag, xc7_lut=lut, xc7_lutram=x.get("RAM32M", 0)*4 + x.get("RAM64M", 0)*4,
                     xc7_ff=ff, xc7_dsp=x.get("DSP48E1", 0), xc7_carry4=x.get("CARRY4", 0),
                     ecp5_lut4=pnr_util(tag, "LUT4s"), ecp5_ff=pnr_util(tag, "DFFs"),
                     ecp5_mult18=e.get("MULT18X18D", 0), ecp5_ccu2=e.get("CCU2C", 0),
                     fmax_mhz=fmax(tag)))
with open(DOC/"resource_timing.csv", "w") as f:
    w = csv.DictWriter(f, fieldnames=rows[0].keys()); w.writeheader(); w.writerows(rows)

# ---- performance sweep from simulation ----
perf, perfp = {}, {}
for line in (ROOT/"sim/perf_sweep.txt").read_text().splitlines():
    m = re.match(r"(PERF|PERFPIPE) N=(\d+) systolic=(\d+) sequential=(\d+)", line)
    if m:
        (perf if m.group(1) == "PERF" else perfp)[int(m.group(2))] = (int(m.group(3)), int(m.group(4)))
Ns = sorted(perf)
with open(DOC/"cycle_sweep.csv", "w") as f:
    w = csv.writer(f); w.writerow(["N", "systolic_cycles", "systolic_pipe_cycles", "sequential_cycles",
                                   "formula_sys_3N+1", "formula_seq_N2(N+1)+1", "speedup_cycles", "MACs"])
    for n in Ns:
        s, q = perf[n]
        w.writerow([n, s, perfp[n][0], q, 3*n+1, n*n*(n+1)+1, round(q/s, 2), n**3])

# ---- figures ----
plt.rcParams.update({"font.size": 10, "figure.dpi": 160})
fig, ax = plt.subplots(figsize=(5.2, 3.4))
ax.plot(Ns, [perf[n][1] for n in Ns], "o-", label="Sequential (1 MAC)")
ax.plot(Ns, [perf[n][0] for n in Ns], "s-", label="Systolic N×N")
ax.plot(Ns, [perfp[n][0] for n in Ns], "^--", label="Systolic, pipelined MAC")
ax.set_yscale("log"); ax.set_xlabel("Matrix size N"); ax.set_ylabel("Latency (clock cycles, log)")
ax.set_title("Measured latency for one N×N matmul"); ax.grid(alpha=.3, which="both"); ax.legend()
fig.tight_layout(); fig.savefig(FIG/"latency_vs_N.png"); plt.close(fig)

fig, ax = plt.subplots(figsize=(5.2, 3.4))
ax.bar([str(n) for n in Ns], [perf[n][1]/perf[n][0] for n in Ns], color="#3b7dd8")
for i, n in enumerate(Ns):
    ax.text(i, perf[n][1]/perf[n][0], f"{perf[n][1]/perf[n][0]:.1f}×", ha="center", va="bottom", fontsize=8)
ax.set_xlabel("Matrix size N"); ax.set_ylabel("Speed-up (cycles)")
ax.set_title("Systolic speed-up over sequential baseline"); ax.grid(axis="y", alpha=.3)
fig.tight_layout(); fig.savefig(FIG/"speedup_vs_N.png"); plt.close(fig)

fig, ax = plt.subplots(figsize=(5.2, 3.4))
ax.plot(Ns, [n**3/perf[n][0] for n in Ns], "s-", label="Systolic: measured MAC/cycle")
ax.plot(Ns, [n*n for n in Ns], "k:", label="Systolic peak N² MAC/cycle")
ax.plot(Ns, [n**3/perf[n][1] for n in Ns], "o-", label="Sequential MAC/cycle")
ax.set_xlabel("Matrix size N"); ax.set_ylabel("MACs per cycle"); ax.grid(alpha=.3); ax.legend(fontsize=8)
ax.set_title("Throughput (MAC operations per clock)")
fig.tight_layout(); fig.savefig(FIG/"throughput_vs_N.png"); plt.close(fig)

# ---- summary markdown ----
r = {d["tag"]: d for d in rows}
def gops(n, cyc, f): return 2*n**3/cyc*f/1e3  # GOPS (1 MAC = 2 ops)
out = ["# Results summary (auto-generated by scripts/analyze.py)\n",
       "## Resource utilisation and Fmax\n",
       "| Design | Artix-7 LUT | LUTRAM | FF | DSP48E1 | ECP5 LUT4 (P&R, incl. carry) | ECP5 FF | MULT18 | Fmax ECP5 (MHz, P&R) |",
       "|---|---|---|---|---|---|---|---|---|"]
for d in rows:
    out.append(f"| {d['design']} | {d['xc7_lut']} | {d['xc7_lutram']} | {d['xc7_ff']} | {d['xc7_dsp']} | "
               f"{d['ecp5_lut4']} | {d['ecp5_ff']} | {d['ecp5_mult18']} | {d['fmax_mhz']:.2f} |")
out += ["\n## Latency (measured in simulation, start -> done)\n",
        "| N | Systolic | Systolic (pipe) | Sequential | Speed-up | MACs |", "|---|---|---|---|---|---|"]
for n in Ns:
    s, q = perf[n]
    out.append(f"| {n} | {s} | {perfp[n][0]} | {q} | {q/s:.2f}× | {n**3} |")
out += ["\n## Wall-clock comparison at the measured Fmax\n",
        "| Design | Cycles | Fmax (MHz) | Latency (ns) | Throughput (GOPS) |", "|---|---|---|---|---|"]
for tag, n, cyc in [("systolic_top_N4", 4, perf[4][0]), ("systolic_top_N4_pipe", 4, perfp[4][0]),
                    ("sequential_matmul_N4", 4, perf[4][1]), ("systolic_top_N3", 3, perf[3][0]),
                    ("sequential_matmul_N3", 3, perf[3][1])]:
    f = r[tag]["fmax_mhz"]
    out.append(f"| {r[tag]['design']} | {cyc} | {f:.2f} | {cyc*1e3/f:.1f} | {gops(n, cyc, f):.3f} |")
(DOC/"results_summary.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
